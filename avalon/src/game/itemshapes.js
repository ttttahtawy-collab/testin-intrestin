const geoCache = new Map();
export function itemShape(id) {
  const key = SHAPE_OF[id] || id;
  const s = S[key];
  if (!s) return null;
  return {
    ...s,
    geom: (px) => {
      const k = key + ':' + px.toFixed(4);
      let g = geoCache.get(k);
      if (!g) { g = boxShape(s.boxes, px); geoCache.set(k, g); }
      return g;
    },
  };
}
